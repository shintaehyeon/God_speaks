import 'package:flutter/material.dart';

class HISpeakLocalizations {
  final Locale locale;

  const HISpeakLocalizations(this.locale);

  static const supportedLocales = [Locale('ko'), Locale('ja'), Locale('fr')];

  static HISpeakLocalizations of(BuildContext context) {
    return Localizations.of<HISpeakLocalizations>(
          context,
          HISpeakLocalizations,
        ) ??
        const HISpeakLocalizations(Locale('ko'));
  }

  String get languageCode {
    final code = locale.languageCode;
    return _values.containsKey(code) ? code : 'ko';
  }

  String t(String key) {
    return _values[languageCode]?[key] ?? _values['ko']?[key] ?? key;
  }

  String format(String key, Map<String, String> values) {
    var text = t(key);
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', entry.value);
    }
    return text;
  }
}

extension HISpeakLocalizationsX on BuildContext {
  HISpeakLocalizations get l10n => HISpeakLocalizations.of(this);
}

class HISpeakLocalizationsDelegate
    extends LocalizationsDelegate<HISpeakLocalizations> {
  const HISpeakLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return HISpeakLocalizations.supportedLocales.any(
      (supported) => supported.languageCode == locale.languageCode,
    );
  }

  @override
  Future<HISpeakLocalizations> load(Locale locale) async {
    return HISpeakLocalizations(locale);
  }

  @override
  bool shouldReload(covariant HISpeakLocalizationsDelegate old) => false;
}

